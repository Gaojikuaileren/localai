"""P4-S12 · 助手的**行为底线**提示词。中枢注入,客户端改不掉。

★★★ 起因是一次实机实测(2026-08-05,模型接入当晚的第一轮对话):

    用户:你好
    助手:你好!最近天气不错,适合出去走走。你今天过得怎么样呀?
    用户:你记得我是谁吗
    助手:**当然记得啦!我们之前聊过天气、日常趣事,还有你对未来的期待呢~**

**那段"之前"根本不存在。** 会话就是从「你好」开始的,发上去的历史是 0 条、2 条、4 条,
每一条都来自这一轮。**它在第二轮就凭空捏造了一段共同回忆**,而且说得极其笃定。
用户打了一句「不允许撒谎」它才改口。

根因不是模型坏,是**全链路一句提示词都没有** —— 模型落回了自带的聊天人设,
那种人设的默认行为就是营造熟稔感。

⇒ 这个项目从 P0 起的全部纪律是「**绝不伪造**」:未接入的功能如实说、
   推算值标推算、失败必须长得和成功不一样。而产品面上第一个能开口的东西,
   **第二轮就在编**。这条不补,前面所有的诚实工程在用户眼里都不算数。

────────────────────────────────────────────────────────────────────
★★ 为什么放在**中枢**而不是客户端:

  · 客户端可以漏发、可以被改、将来还会有第二个第三个调用方(桌宠 / Agent / 同传);
  · 一条"靠每个调用方自觉带上"的底线**不是底线**。
  · 与「权限按档位挂载而非运行时判断」(§6.2)同一条纪律:**放在唯一权威那一侧**。

★★ 本文件**只写行为底线,不写人设**。
   叫什么名字、什么语气、用什么称呼 —— 那是用户的裁定,不该由我塞进去。
   两者混在一句里的后果是:调人设时会顺手把底线一起改掉。
"""
from __future__ import annotations

from typing import Dict, List

#: 助手**不得**做的事。★ 每一条都对应一次真实的失败形态,不是泛泛的"要诚实"。
FLOOR = """你是一个在用户自己电脑上运行的本地 AI 助手。以下几条是**行为底线**,任何情况下都不放宽:

1. **不要声称记得没发生过的事。** 你能看到的只有本次请求里给你的这些消息。
   如果用户问「你记得我是谁吗」「我们之前聊过什么」,而给你的消息里没有,
   就直说「这次对话里没有这些信息」——**不要编造共同经历来显得亲切**。
   你没有跨会话的长期记忆(记忆库存在,但目前还没有接到对话上)。

2. **不要声称你有你没有的能力。** 你不能上网、不能读用户的文件、不能操作这台电脑、
   不能发消息。被问到时直接说不能,不要说「我帮你查一下」然后编一个结果。

3. **不确定就说不确定。** 说不准的事标出来是哪里说不准;不要用笃定的语气填补空白。
   宁可回答短一点,也不要为了显得有用而猜。

4. **区分"你的输出"和"事实"。** 你自己创作的内容(诗、代码、例子)要说明是你写的;
   引用的内容要说清出处;记不清出处就说记不清。

5. 用用户使用的语言回答。默认简体中文。"""


def build(existing: List[Dict] | None = None) -> Dict:
    """构造要注入的 system 消息。"""
    return {"role": "system", "content": FLOOR}


def ensure(messages: List[Dict]) -> List[Dict]:
    """把行为底线放到消息列表最前面。

    ★ 调用方已有 system 消息时**不覆盖、不删除**,而是把底线**放在它前面** ——
      用户/上层可以追加自己的指示,但**删不掉底线**。
      (覆盖的话,一个带 system 的调用方就能把底线整个绕开;
       删除的话,用户的自定义指示会莫名其妙消失。)
    ★ 幂等:已经注入过就不再注入 —— 否则每次转发都会多叠一层。
    """
    out = list(messages or [])
    for m in out:
        if isinstance(m, dict) and m.get("role") == "system" and m.get("content") == FLOOR:
            return out            # 已经有了
    return [build()] + out
