from typing import Set

import e1_detector as _e1

# 同形复用:结果对象只需要 .categories(命中了哪几类)与 .blocked(要不要拦)。
# 不另造一个类 —— 两个几乎一样的结果类型迟早会分叉,而分叉的那一刻就是漏洞。
E4Result = _e1.E1Result


def scan(text: str) -> E4Result:
    """扫描将要出境的整份载荷。

    ★ 注意签名里【没有】override / 档位 / 白名单参数,而且以后也不该有 ——
      见模块头:出境的放行能力必须在结构上不存在,而不是"默认关着"。
    """
    return _e1.scan(text or "")


def block_message(categories: Set[str]) -> str:
    """拦下之后给用户看的话。

    ★ 与 E1 的措辞【必须不同】:E1 说的是"可以放行但你要确认",
      E4 说的是"这条路没有放行"。把两者写成一样,用户会去找那个并不存在的按钮。
    """
    labels = "、".join(_e1._CAT_LABEL.get(c, c) for c in sorted(categories))
    return (
        f"已拦截:要发出去的内容里检测到凭证类信息({labels})。\n"
        "这个后端在你的控制之外,内容一旦发出就收不回来 —— 所以出境闸不提供放行选项。\n"
        "请把这些内容从对话里去掉再重试;确实需要它参与的活,请交给本地模型做。"
    )
